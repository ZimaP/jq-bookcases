#!/usr/bin/env node

import { readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join, posix } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  PHOTOREAL_MATRIX_INVALID_COUNT,
  PHOTOREAL_MATRIX_MANIFEST_KIND,
  PHOTOREAL_MATRIX_MANIFEST_SCHEMA_VERSION,
  PHOTOREAL_MATRIX_MASTER_ROOT,
  PHOTOREAL_MATRIX_PIPELINE_VERSION,
  PHOTOREAL_MATRIX_VALID_COUNT,
  discoverPhotorealMatrix,
  hashCanonical,
  masterPathFor,
  publishedPathFor
} from "../tools/blender/photoreal-matrix-contract.mjs";

const SCRIPT_DIRECTORY = dirname(fileURLToPath(import.meta.url));
export const PHOTOREAL_REGISTRY_REPOSITORY_ROOT = join(SCRIPT_DIRECTORY, "..");
export const PHOTOREAL_REGISTRY_MANIFEST_PATH = join(
  PHOTOREAL_REGISTRY_REPOSITORY_ROOT,
  "config/photoreal-preview-matrix-provenance.json"
);
export const PHOTOREAL_REGISTRY_OUTPUT_PATH = join(
  PHOTOREAL_REGISTRY_REPOSITORY_ROOT,
  "guided-published-preview-registry.generated.js"
);

const SHA40_RE = /^[a-f0-9]{40}$/;
const SHA256_RE = /^[a-f0-9]{64}$/;

export function createPublishedPreviewRegistrySource(manifest) {
  const records = validateAndExtractPublishedRecords(manifest);
  const metadata = {
    schemaVersion: 1,
    pipelineVersion: manifest.pipelineVersion,
    sourceCommit: manifest.sourceCommit,
    generatedAt: manifest.generatedAt,
    manifestSha256: manifest.manifestSha256,
    publishedCount: records.length
  };
  const renderedRecords = records.map((record) => (
    `  Object.freeze(${indentJson(record, 2)})`
  )).join(",\n");

  return `// Generated by npm run preview:sync-registry. Do not edit by hand.\n`
    + `export const PUBLISHED_PHOTOREAL_MATRIX_METADATA = Object.freeze(${JSON.stringify(metadata, null, 2)});\n\n`
    + `export const PUBLISHED_PHOTOREAL_MATRIX_ASSETS = Object.freeze([\n${renderedRecords}\n]);\n`;
}

export function validateAndExtractPublishedRecords(manifest) {
  assert(manifest && typeof manifest === "object" && !Array.isArray(manifest), "Manifest must be an object.");
  assert(
    JSON.stringify(Object.keys(manifest).sort()) === JSON.stringify([
      "authoritativeSources", "counts", "entries", "failures", "generatedAt", "kind",
      "manifestSha256", "pipelineVersion", "schemaVersion", "sourceCommit"
    ]),
    "Manifest has unknown or missing top-level fields."
  );
  assert(manifest.kind === PHOTOREAL_MATRIX_MANIFEST_KIND, `Manifest kind must be ${PHOTOREAL_MATRIX_MANIFEST_KIND}.`);
  assert(manifest.schemaVersion === PHOTOREAL_MATRIX_MANIFEST_SCHEMA_VERSION, `Manifest schema version must be ${PHOTOREAL_MATRIX_MANIFEST_SCHEMA_VERSION}.`);
  assert(manifest.pipelineVersion === PHOTOREAL_MATRIX_PIPELINE_VERSION, `Manifest pipeline must be ${PHOTOREAL_MATRIX_PIPELINE_VERSION}.`);
  assert(SHA40_RE.test(manifest.sourceCommit || ""), "Manifest sourceCommit must be a full lowercase Git SHA.");
  assert(isIsoTimestamp(manifest.generatedAt), "Manifest generatedAt timestamp is invalid.");
  assert(SHA256_RE.test(manifest.manifestSha256 || ""), "Manifest manifestSha256 is invalid.");
  const { manifestSha256, ...payload } = manifest;
  assert(hashCanonical(payload) === manifestSha256, "Manifest canonical SHA-256 does not match its content.");
  assert(
    manifest.counts?.products === 7
      && manifest.counts?.layouts === 10
      && manifest.counts?.total === 70
      && manifest.counts?.valid === PHOTOREAL_MATRIX_VALID_COUNT
      && manifest.counts?.unavailable === PHOTOREAL_MATRIX_INVALID_COUNT
      && manifest.counts?.published === PHOTOREAL_MATRIX_VALID_COUNT
      && manifest.counts?.pending === 0
      && manifest.counts?.failed === 0,
    "Registry generation requires the complete 50-published / 20-unavailable matrix."
  );
  assert(Array.isArray(manifest.failures) && manifest.failures.length === 0, "Registry generation refuses a manifest with render failures.");
  assert(Array.isArray(manifest.entries) && manifest.entries.length === 70, "Manifest must enumerate all 70 product/layout pairs.");

  const matrix = discoverPhotorealMatrix();
  const records = [];
  const keys = new Set();
  const assets = new Set();
  for (const [index, entry] of manifest.entries.entries()) {
    const authoritative = matrix.combinations[index];
    assert(entry && typeof entry === "object", "Manifest entries must be objects.");
    assert(typeof entry.key === "string" && !keys.has(entry.key), `Missing or duplicate matrix key: ${entry.key || "(missing)"}.`);
    keys.add(entry.key);
    assert(
      entry.key === authoritative.key
        && entry.productId === authoritative.productId
        && entry.layoutId === authoritative.layoutId
        && entry.productLabel === authoritative.productLabel
        && entry.layoutLabel === authoritative.layoutLabel
        && entry.compatibilityStatus === authoritative.compatibilityStatus
        && entry.valid === authoritative.valid
        && entry.publishedPath === authoritative.publishedPath
        && entry.masterPath === authoritative.masterPath,
      `${entry.key} differs from the authoritative guided matrix.`
    );
    assert(entry.lastFailure === null, `${entry.key} retains a render failure.`);
    if (!entry.valid) {
      assert(entry.renderStatus === "unavailable" && entry.provenance === null, `${entry.key} is invalid but appears published.`);
      continue;
    }

    const provenance = entry.provenance;
    const published = provenance?.publishedAsset;
    const master = provenance?.masterAsset;
    assert(entry.renderStatus === "published" && provenance, `${entry.key} has no published provenance.`);
    assert(
      provenance.key === entry.key
        && provenance.productId === entry.productId
        && provenance.layoutId === entry.layoutId,
      `${entry.key} provenance identifies another pair.`
    );
    assert(provenance.sourceCommit === manifest.sourceCommit, `${entry.key} source commit differs from the manifest.`);
    assert(provenance.sourceFinish === "natural-oak", `${entry.key} does not use the canonical Natural Oak visualization.`);
    assert(provenance.sourceCommand === `npm run blender:photoreal-matrix -- --only ${entry.key}`, `${entry.key} source command is stale.`);
    assert(isIsoTimestamp(provenance.generatedAt), `${entry.key} provenance timestamp is invalid.`);
    assert(/^jq-photoreal-preview-matrix-v1-[a-f0-9]{64}$/.test(provenance.packageKey || ""), `${entry.key} package key is invalid.`);
    assertSafeAsset(published, publishedPathFor(entry.productId, entry.layoutId), "image/webp", entry.key);
    assertSafeAsset(master, masterPathFor(entry.productId, entry.layoutId), "image/png", entry.key);
    assert(master.colorDepth === 16, `${entry.key} master PNG must retain 16-bit color depth.`);
    const expectedArtifactRoot = `${PHOTOREAL_MATRIX_MASTER_ROOT}/${entry.productId}/${entry.layoutId}`;
    assert(
      provenance.artifactPaths
        && JSON.stringify(Object.keys(provenance.artifactPaths).sort()) === JSON.stringify(["blend", "package", "result"])
        && provenance.artifactPaths.blend === `${expectedArtifactRoot}/preview-v1.blend`
        && provenance.artifactPaths.package === `${expectedArtifactRoot}/render-package.json`
        && provenance.artifactPaths.result === `${expectedArtifactRoot}/render-result.json`,
      `${entry.key} renderer artifact paths are incomplete or stale.`
    );
    assert(!assets.has(published.path), `Duplicate published asset path ${published.path}.`);
    assets.add(published.path);

    for (const [name, value] of Object.entries({
      geometryFingerprint: provenance.geometryFingerprint,
      selectionFingerprint: provenance.selectionFingerprint,
      specificationFingerprint: provenance.specificationFingerprint
    })) {
      assert(/^jq-guided-[a-z0-9-]+-v[0-9]+-[a-z0-9]+$/i.test(value || ""), `${entry.key} has an invalid ${name}.`);
    }

    records.push({
      key: entry.key,
      productId: entry.productId,
      productLabel: entry.productLabel,
      layoutId: entry.layoutId,
      layoutLabel: entry.layoutLabel,
      compatibilityStatus: entry.compatibilityStatus,
      asset: published.path,
      assetSha256: published.sha256,
      assetBytes: published.bytes,
      masterAsset: master.path,
      masterAssetSha256: master.sha256,
      masterAssetBytes: master.bytes,
      sourceFinish: provenance.sourceFinish,
      geometryFingerprint: provenance.geometryFingerprint,
      selectionFingerprint: provenance.selectionFingerprint,
      specificationFingerprint: provenance.specificationFingerprint,
      packageKey: provenance.packageKey
    });
  }

  assert(records.length === PHOTOREAL_MATRIX_VALID_COUNT, `Expected ${PHOTOREAL_MATRIX_VALID_COUNT} published registry records; received ${records.length}.`);
  return Object.freeze(records.map((record) => Object.freeze(record)));
}

export async function syncPublishedPreviewRegistry(options = {}) {
  const manifestPath = options.manifestPath || PHOTOREAL_REGISTRY_MANIFEST_PATH;
  const outputPath = options.outputPath || PHOTOREAL_REGISTRY_OUTPUT_PATH;
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  const source = createPublishedPreviewRegistrySource(manifest);
  if (options.check === true) {
    const current = await readFile(outputPath, "utf8");
    assert(current === source, "Generated published-preview registry is stale. Run npm run preview:sync-registry.");
    return Object.freeze({ mode: "check", outputPath, count: PHOTOREAL_MATRIX_VALID_COUNT });
  }
  const temporaryPath = `${outputPath}.tmp-${process.pid}`;
  try {
    await writeFile(temporaryPath, source, "utf8");
    await rename(temporaryPath, outputPath);
  } finally {
    await rm(temporaryPath, { force: true });
  }
  return Object.freeze({ mode: "write", outputPath, count: PHOTOREAL_MATRIX_VALID_COUNT });
}

function assertSafeAsset(asset, expectedPath, mimeType, key) {
  assert(asset && typeof asset === "object", `${key} asset metadata is missing.`);
  assert(asset.path === expectedPath && asset.path === posix.normalize(asset.path) && !asset.path.includes(".."), `${key} asset path is invalid.`);
  assert(asset.mimeType === mimeType, `${key} asset MIME type is invalid.`);
  assert(asset.width === 1920 && asset.height === 1280, `${key} asset dimensions must be 1920×1280.`);
  assert(Number.isSafeInteger(asset.bytes) && asset.bytes > 0, `${key} asset byte count is invalid.`);
  assert(SHA256_RE.test(asset.sha256 || ""), `${key} asset SHA-256 is invalid.`);
}

function indentJson(value, spaces) {
  const indent = " ".repeat(spaces);
  return JSON.stringify(value, null, 2).replace(/\n/g, `\n${indent}`);
}

function isIsoTimestamp(value) {
  if (typeof value !== "string" || !value) return false;
  const timestamp = Date.parse(value);
  return Number.isFinite(timestamp) && new Date(timestamp).toISOString() === value;
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

async function main() {
  const argumentsList = process.argv.slice(2);
  assert(argumentsList.every((argument) => argument === "--check"), `Unknown argument: ${argumentsList.find((argument) => argument !== "--check")}.`);
  const result = await syncPublishedPreviewRegistry({ check: argumentsList.includes("--check") });
  console.log(`${result.mode === "check" ? "Verified" : "Wrote"} ${result.count} published preview records: ${result.outputPath}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
